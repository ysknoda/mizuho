"""Read a crystal structure from a CIF file.

Written in-house (no CIF library dependency) and deliberately narrow: the
first data block's cell, symmetry operations, and atom-site loop. Handles
both symmetry-operation tags (`_symmetry_equiv_pos_as_xyz`,
`_space_group_symop_operation_xyz`), standard uncertainties in
parentheses, quoted values, comments and semicolon text fields.

Conversion into mizuho's own setting and Wyckoff letters is not done here
but by mizuho.symmetry.to_mizuho, which idealises the rounded special
positions published CIFs contain.
"""

import re
from dataclasses import dataclass, field
from fractions import Fraction
from pathlib import Path

import numpy as np

from ..lattice import build_lattice_matrix

_SYMOP_TAGS = ("_symmetry_equiv_pos_as_xyz", "_space_group_symop_operation_xyz")
_SG_NUMBER_TAGS = ("_space_group_it_number", "_symmetry_int_tables_number")

# Two expanded atoms closer than this (A) are one atom seen twice: the
# same site regenerated by different operations, which a rounded special
# position leaves ~1e-3 A apart. Real interatomic distances are > 0.5 A.
_DUPLICATE_TOL = 0.05


@dataclass
class CifSite:
    label: str
    element: str
    frac: np.ndarray
    occupancy: float = 1.0


@dataclass
class CifStructure:
    cell: dict[str, float]  # a b c alpha beta gamma
    symops: list[tuple[np.ndarray, np.ndarray]]
    sites: list[CifSite]
    spacegroup: int | None  # declared number, if any
    source: str = ""
    skipped: list[str] = field(default_factory=list)

    @property
    def lattice(self) -> np.ndarray:
        return build_lattice_matrix(self.cell)

    def expand(self) -> tuple[np.ndarray, np.ndarray, list[str]]:
        """Every atom of the cell: (lattice, frac (N, 3), species)."""
        lat = self.lattice
        frac, species = [], []
        for site in self.sites:
            for R, t in self.symops:
                p = (R @ site.frac + t) % 1.0
                if any(
                    _same_point(p, q, lat)
                    for q, s in zip(frac, species)
                    if s == site.element
                ):
                    continue
                for q, s in zip(frac, species):
                    if s != site.element and _same_point(p, q, lat):
                        raise ValueError(
                            f"{site.label} ({site.element}) coincides with "
                            f"a {s} atom at {q}"
                        )
                frac.append(p)
                species.append(site.element)
        return lat, np.array(frac), species


def _same_point(p, q, lat) -> bool:
    d = p - q
    d -= np.round(d)
    return float(np.linalg.norm(d @ lat)) < _DUPLICATE_TOL


# ---------------------------------------------------------------------------
# Tokeniser and block parser
# ---------------------------------------------------------------------------


class _Value(str):
    """A quoted or text-field token: always a value, even when it begins
    with '_' or reads like a keyword (pyrite.cif quotes data names as
    values in its publcif loops)."""


def _is_tag(tok) -> bool:
    return tok.startswith("_") and not isinstance(tok, _Value)


def _is_word(tok, word: str) -> bool:
    return not isinstance(tok, _Value) and tok.lower() == word


def _tokens(text: str):
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith(";"):
            buf = [line[1:]]
            i += 1
            while i < len(lines) and not lines[i].startswith(";"):
                buf.append(lines[i])
                i += 1
            yield _Value("\n".join(buf).strip())
            i += 1
            continue
        j, n = 0, len(line)
        while j < n:
            ch = line[j]
            if ch.isspace():
                j += 1
            elif ch == "#":
                break
            elif ch in "'\"":
                # A quote closes only when followed by whitespace or EOL.
                k = j + 1
                while k < n and not (
                    line[k] == ch and (k + 1 == n or line[k + 1].isspace())
                ):
                    k += 1
                yield _Value(line[j + 1 : k])
                j = k + 1
            else:
                k = j
                while k < n and not line[k].isspace():
                    k += 1
                yield line[j:k]
                j = k
        i += 1


def _parse_block(
    text: str,
) -> tuple[dict[str, str], list[tuple[list[str], list[list[str]]]]]:
    items: dict[str, str] = {}
    loops: list[tuple[list[str], list[list[str]]]] = []
    toks = list(_tokens(text))
    i, seen_data = 0, False
    while i < len(toks):
        tok = toks[i]
        low = tok.lower()
        if not isinstance(tok, _Value) and low.startswith("data_"):
            if seen_data:
                break                       # first data block only
            seen_data = True
            i += 1
        elif _is_word(tok, "loop_"):
            i += 1
            tags = []
            while i < len(toks) and _is_tag(toks[i]):
                tags.append(toks[i].lower())
                i += 1
            values = []
            while (i < len(toks) and not _is_tag(toks[i]) and not _is_word(toks[i], "loop_")
                   and not (not isinstance(toks[i], _Value)
                            and toks[i].lower().startswith("data_"))):
                values.append(toks[i])
                i += 1
            if tags and len(values) % len(tags):
                raise ValueError(f"loop {tags[0]}: {len(values)} values for {len(tags)} tags")
            rows = [values[k:k + len(tags)] for k in range(0, len(values), len(tags))]
            loops.append((tags, rows))
        elif _is_tag(tok):
            items[low] = toks[i + 1] if i + 1 < len(toks) else ""
            i += 2
        else:
            i += 1
    return items, loops


def _number(value: str) -> float | None:
    """CIF numeric value: standard uncertainty in parentheses stripped;
    '.' and '?' (inapplicable / unknown) are None."""
    if value in (".", "?"):
        return None
    return float(re.sub(r"\(\d+\)$", "", value))


_TERM = re.compile(r"([+-]?)([^+-]+)")


def parse_symop(expr: str) -> tuple[np.ndarray, np.ndarray]:
    """'x-y,-y,2/3-z' -> (R, t)."""
    parts = [p.strip().lower().replace(" ", "") for p in expr.split(",")]
    if len(parts) != 3:
        raise ValueError(f"symmetry operation {expr!r} does not have 3 components")
    R = np.zeros((3, 3))
    t = np.zeros(3)
    for row, part in enumerate(parts):
        for sign, body in _TERM.findall(part):
            s = -1.0 if sign == "-" else 1.0
            var = body[-1] if body[-1] in "xyz" else None
            if var is None:
                t[row] += s * float(Fraction(body))
            else:
                coeff = body[:-1].rstrip("*")
                k = float(Fraction(coeff)) if coeff else 1.0
                R[row, "xyz".index(var)] += s * k
    return R, t


_ELEMENTS = set("""
H He Li Be B C N O F Ne Na Mg Al Si P S Cl Ar K Ca Sc Ti V Cr Mn Fe Co Ni Cu Zn
Ga Ge As Se Br Kr Rb Sr Y Zr Nb Mo Tc Ru Rh Pd Ag Cd In Sn Sb Te I Xe Cs Ba La Ce
Pr Nd Pm Sm Eu Gd Tb Dy Ho Er Tm Yb Lu Hf Ta W Re Os Ir Pt Au Hg Tl Pb Bi Po At Rn
Fr Ra Ac Th Pa U Np Pu Am Cm Bk Cf Es Fm Md No Lr Rf Db Sg Bh Hs Mt Ds Rg Cn Nh Fl
Mc Lv Ts Og""".split())


def _element(symbol: str) -> str:
    """Element of a type symbol or label: 'Fe2+', 'O2-', 'Mg1', and also
    upper-case 'FE' (some programs write it so; read as F it would turn
    pyrite into a fluoride). Two letters win when they name an element."""
    m = re.match(r"([A-Za-z]{1,2})", symbol)
    if not m:
        raise ValueError(f"cannot read an element from {symbol!r}")
    two = m.group(1).capitalize()
    if len(two) == 2 and two in _ELEMENTS:
        return two
    one = two[0]
    if one in _ELEMENTS:
        return one
    raise ValueError(f"cannot read an element from {symbol!r}")


def _loop_with(loops, tag):
    for tags, rows in loops:
        if tag in tags:
            return tags, rows
    return None


# ---------------------------------------------------------------------------
# Public entry point
# ---------------------------------------------------------------------------


def read_cif(path) -> CifStructure:
    text = Path(path).read_text()
    items, loops = _parse_block(text)

    cell = {}
    for key in ("a", "b", "c"):
        cell[key] = _number(items[f"_cell_length_{key}"])
    for key in ("alpha", "beta", "gamma"):
        cell[key] = _number(items.get(f"_cell_angle_{key}", "90"))

    symops = []
    for tag in _SYMOP_TAGS:
        found = _loop_with(loops, tag)
        if found:
            tags, rows = found
            col = tags.index(tag)
            symops = [parse_symop(r[col]) for r in rows]
            break
    if not symops:
        raise ValueError(f"{path}: no symmetry operations ({' or '.join(_SYMOP_TAGS)})")

    spacegroup = None
    for tag in _SG_NUMBER_TAGS:
        if tag in items and _number(items[tag]) is not None:
            spacegroup = int(_number(items[tag]))
            break

    found = _loop_with(loops, "_atom_site_fract_x")
    if not found:
        raise ValueError(f"{path}: no _atom_site loop")
    tags, rows = found
    col = {t: tags.index(t) for t in tags}
    sites, skipped = [], []
    for r in rows:
        label = r[col["_atom_site_label"]] if "_atom_site_label" in col else "?"
        flag = (
            r[col["_atom_site_calc_flag"]].lower()
            if "_atom_site_calc_flag" in col
            else ""
        )
        if flag == "dum":
            # A dummy atom (e.g. a hydrogen whose position was never
            # determined) is not part of the refined structure.
            skipped.append(label)
            continue
        symbol = (
            r[col["_atom_site_type_symbol"]]
            if "_atom_site_type_symbol" in col
            else label
        )
        occ = (
            _number(r[col["_atom_site_occupancy"]])
            if "_atom_site_occupancy" in col
            else None
        )
        occ = 1.0 if occ is None else occ
        if abs(occ - 1.0) > 1e-6:
            raise ValueError(
                f"{path}: {label} has occupancy {occ}; mizuho models "
                f"fully ordered structures only"
            )
        frac = np.array([_number(r[col[f"_atom_site_fract_{k}"]]) for k in "xyz"])
        sites.append(CifSite(label, _element(symbol), frac, occ))

    return CifStructure(cell, symops, sites, spacegroup, str(path), skipped)


def cif_to_mizuho(path, symprec: float | None = None):
    """Read a CIF and express it in mizuho's setting of its declared
    space group (mizuho.symmetry.to_mizuho). The group is taken from the
    CIF's IT-number tag, or detected from its expanded structure when the
    file declares none."""
    from ..symmetry import detect_spacegroup, to_mizuho

    cif = read_cif(path)
    lat, frac, species = cif.expand()
    sg = cif.spacegroup
    if sg is None:
        sg = detect_spacegroup(lat, frac, species, 1e-3)[0]
    try:
        return to_mizuho(lat, frac, species, sg, symprec=symprec)
    except ValueError:
        # A structure can hold MORE symmetry than its file declares (an
        # optimised structure written in the group it was optimised in).
        # spglib then only reports the supergroup, so when the file is
        # already in mizuho's setting its sites are read directly.
        direct = _in_mizuho_setting(cif, sg)
        if direct is None:
            raise
        return direct


def _in_mizuho_setting(cif: "CifStructure", sg: int):
    """The CIF's sites as a mizuho assignment of `sg`, when the file's
    symmetry operations are exactly mizuho's for `sg`; else None."""
    from ..data import WYCKOFF_DB, get_ops
    from ..symmetry import MizuhoStructure, lattice_vector, solve_free_params

    def key(R, t):
        return tuple(np.rint(R).astype(int).ravel()) + tuple(np.round(t % 1.0, 6) % 1.0)

    rot, tr = get_ops(sg)
    if {key(R, t) for R, t in cif.symops} != {key(R, t) for R, t in zip(rot, tr)}:
        return None
    specs, params = [], []
    for site in cif.sites:
        # The most special position the atom lies on is its Wyckoff letter.
        for entry in sorted(WYCKOFF_DB[sg], key=lambda e: (e.multiplicity, len(e.free_params))):
            values = solve_free_params(sg, entry, site.frac, tol=1e-4)
            if values is not None:
                specs.append({"element": site.element, "letter": entry.letter})
                params.extend(values[n] for n in entry.free_params)
                break
        else:
            return None
    pv = np.array(lattice_vector(sg, cif.lattice) + params, dtype=float)
    return MizuhoStructure(sg, specs, pv, 0.0)


