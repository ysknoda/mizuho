def format_symop(R: np.ndarray, t: np.ndarray) -> str:
    """(R, t) -> 'x-y,-y,2/3-z' style string (inverse of parse_symop)."""
    comps = []
    for row, ti in zip(R, t):
        terms = ""
        for c, v in zip(row, "xyz"):
            c = int(round(c))
            if c:
                terms += ("+" if c > 0 else "-") + (f"{abs(c)}*" if abs(c) != 1 else "") + v
        frac = Fraction(float(ti) % 1.0).limit_denominator(24)
        if frac:
            terms += f"+{frac}"
        comps.append(terms.lstrip("+") or "0")
    return ",".join(comps)


def write_cif(param_vector, config: dict, path, title: str = "mizuho") -> None:
    """Write a structure in its space group: symmetry operations plus one
    representative atom per Wyckoff site, in mizuho's setting."""
    from ..data import build_point, get_ops
    from ..structure import build_structure

    sg = config["spacegroup"]
    st = build_structure(np.asarray(param_vector, float), config)
    lp = st["lattice_params"]
    lat = st["lattice_matrix"]
    volume = abs(float(np.dot(lat[0], np.cross(lat[1], lat[2]))))

    n_lat = len(param_vector) - sum(len(s["free_params"]) for s in config["wyckoff_sites"])
    values = list(np.asarray(param_vector, float)[n_lat:])

    lines = [f"data_{re.sub(r'[^A-Za-z0-9_]', '_', title)}",
             "_audit_creation_method 'mizuho'",
             f"_space_group_IT_number {sg}"]
    if config.get("spacegroup_symbol"):
        lines.append(f"_space_group_name_H-M_alt '{config['spacegroup_symbol']}'")
    for k in ("a", "b", "c"):
        lines.append(f"_cell_length_{k} {float(lp[k]):.6f}")
    for k in ("alpha", "beta", "gamma"):
        lines.append(f"_cell_angle_{k} {float(lp.get(k, 90.0)):.4f}")
    lines.append(f"_cell_volume {volume:.4f}")
    lines += ["", "loop_", "_space_group_symop_id", "_space_group_symop_operation_xyz"]
    rot, tr = get_ops(sg)
    for k, (R, t) in enumerate(zip(rot, tr), 1):
        lines.append(f"{k} '{format_symop(R, t)}'")
    lines += ["", "loop_", "_atom_site_label", "_atom_site_type_symbol",
              "_atom_site_symmetry_multiplicity", "_atom_site_Wyckoff_symbol",
              "_atom_site_fract_x", "_atom_site_fract_y", "_atom_site_fract_z",
              "_atom_site_occupancy"]
    counts: Dict[str, int] = {}
    for site in config["wyckoff_sites"]:
        fp = site["free_params"]
        pv = dict(zip(fp, values[:len(fp)]))
        values = values[len(fp):]
        p = build_point(site["coord_template"], pv) % 1.0
        el = site["element"]
        counts[el] = counts.get(el, 0) + 1
        lines.append(f"{el}{counts[el]} {el} {site['multiplicity']} {site['wyckoff_letter']} "
                     f"{p[0]:.6f} {p[1]:.6f} {p[2]:.6f} 1")
    Path(path).write_text("\n".join(lines) + "\n")
