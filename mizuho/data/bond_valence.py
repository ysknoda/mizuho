def r0(cation: str, valence: int, anion: str):
    """R0 for a cation-anion bond, or None if the paper gives none.
    O, F and Cl come from Table 2 at the cation's oxidation state; the other
    anions from Table 3, which has none."""
    if anion in ("O", "F", "Cl"):
        entry = TABLE2.get((cation, int(valence)))
        return None if entry is None else entry[anion][0]
    return TABLE3.get(cation, {}).get(anion)
