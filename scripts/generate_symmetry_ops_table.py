#!/usr/bin/env python3
"""
Dev-only, one-shot generator for mizuho/data/symmetry_ops.py.

Not part of the shipped package -- run manually (requires the `spglib`
test/dev dependency) whenever the table needs to be regenerated, then
commit the resulting symmetry_ops.py as static data. End users of the
installed `mizuho` package never need spglib at runtime: the generic
orbit-expansion mechanism in data/_orbit.py only does plain numpy
matrix arithmetic over this pre-computed operation list.

For each of the 230 space group numbers, records every symmetry
operation (rotation matrix + translation vector) from spglib's
symmetry database, using the first Hall number (i.e. the default/
standard setting) associated with that space group number. This one
static table is what lets every Wyckoff position's orbit -- general or
special -- be expanded generically at runtime instead of via 1,301
hand-written per-position lambdas.
"""

import sys
from pathlib import Path

import spglib

OUTPUT_PATH = (Path(__file__).resolve().parent.parent
               / "mizuho" / "data" / "symmetry_ops.py")


def build_table():
    sg_to_hall = {}
    for hall in range(1, 531):
        info = spglib.get_spacegroup_type(hall)
        if info.number not in sg_to_hall:
            sg_to_hall[info.number] = hall
    if len(sg_to_hall) != 230:
        raise RuntimeError(f"expected 230 space groups, got {len(sg_to_hall)}")

    table = {}
    for sg, hall in sg_to_hall.items():
        ops = spglib.get_symmetry_from_database(hall)
        rotations = [r.tolist() for r in ops["rotations"]]
        translations = [[round(float(x), 12) for x in t] for t in ops["translations"]]
        table[sg] = (rotations, translations)
    return table


def validate(table):
    if len(table) != 230:
        raise AssertionError(f"expected 230 entries, got {len(table)}")
    for sg, (rotations, translations) in table.items():
        if len(rotations) != len(translations):
            raise AssertionError(f"SG{sg}: rotation/translation count mismatch")
        if len(rotations) < 1:
            raise AssertionError(f"SG{sg}: no operations at all")
        # identity must always be present
        if not any(r == [[1, 0, 0], [0, 1, 0], [0, 0, 1]] and
                   all(abs(x) < 1e-9 for x in t)
                   for r, t in zip(rotations, translations)):
            raise AssertionError(f"SG{sg}: identity operation missing")
    print(f"Validation OK: 230 space groups, "
          f"{sum(len(r) for r, _ in table.values())} total operations.")


def write_output(table):
    lines = []
    lines.append('"""Full symmetry-operation list (rotation + translation) for')
    lines.append("all 230 space groups, in each SG number's default/standard")
    lines.append("setting.")
    lines.append("")
    lines.append("Auto-generated by scripts/generate_symmetry_ops_table.py from")
    lines.append("spglib.get_symmetry_from_database(). This is the sole source of")
    lines.append("truth the generic orbit-expansion mechanism (data/_orbit.py)")
    lines.append("uses to expand ANY Wyckoff position's representative point into")
    lines.append("its full symmetry orbit -- replacing the 1,301 hand-written")
    lines.append("per-position generator lambdas from the original implementation.")
    lines.append("")
    lines.append("Do not edit by hand -- regenerate via:")
    lines.append("    python scripts/generate_symmetry_ops_table.py")
    lines.append('"""')
    lines.append("")
    lines.append("from typing import Dict, List, Tuple")
    lines.append("")
    lines.append("# {sg: (rotations, translations)}")
    lines.append("# rotations[i]: 3x3 int rotation matrix (list of 3 rows)")
    lines.append("# translations[i]: 3-vector (fractional, rounded to 1e-12)")
    lines.append("SYMMETRY_OPS_OF_SG: Dict[int, Tuple[List[List[List[int]]], List[List[float]]]] = {")
    for sg in range(1, 231):
        rotations, translations = table[sg]
        lines.append(f"    {sg}: (")
        lines.append(f"        {rotations!r},")
        lines.append(f"        {translations!r},")
        lines.append("    ),")
    lines.append("}")
    lines.append("")

    OUTPUT_PATH.write_text("\n".join(lines))
    print(f"wrote {OUTPUT_PATH}")


def main():
    table = build_table()
    validate(table)
    write_output(table)


if __name__ == "__main__":
    main()
