#!/usr/bin/env python3
"""
Dev-only, one-shot generator for mizuho/data/point_groups.py.

Not part of the shipped package -- run manually (requires the `spglib`
test/dev dependency) whenever the classification needs to be regenerated,
then commit the resulting point_groups.py as static data. End users of
the installed `mizuho` package never need spglib at runtime.

Derivation
----------
Point group symbol per space group: read directly from spglib's space
group type database (`pointgroup_international`), which is
setting-independent (every Hall-symbol setting of the same space group
number yields the same point group), so any one Hall number per SG is
sufficient.

Symmorphic classification: a space group is symmorphic iff there exists
a point left invariant by its *entire* point group (not just part of
it) -- equivalently, iff the smallest Wyckoff multiplicity in that space
group equals its lattice centering factor (P=1, A/B/C/I=2, F=4, R=3 in
the hexagonal setting). This is computed directly from mizuho's own
WYCKOFF_DB (cross-checked against spglib only for the centering letter),
and was validated against the well-known total of 73 symmorphic space
groups plus 51 hand-picked reference examples spanning all 7 crystal
systems before being adopted here (see the project's development notes/
plan for the full validation transcript) -- run this script's
__main__ block to re-run that validation on demand.
"""

import sys
from pathlib import Path

import spglib

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from mizuho.data import WYCKOFF_DB  # noqa: E402

OUTPUT_PATH = (Path(__file__).resolve().parent.parent
               / "mizuho" / "data" / "point_groups.py")

CENTERING_FACTOR = {"P": 1, "A": 2, "B": 2, "C": 2, "I": 2, "F": 4, "R": 3}

# Spot-check reference set: (SG, expected symmorphic?), hand-picked to
# span all 7 crystal systems and both symmorphic/non-symmorphic cases.
# Re-verified against WYCKOFF_DB + spglib by this script's __main__.
REFERENCE_CHECKS = {
    1: True, 2: True, 3: True, 5: True, 6: True, 8: True,
    10: True, 12: True,
    13: False, 14: False, 15: False,
    16: True, 47: True,
    62: False,
    75: True, 79: True,
    99: True,
    123: True, 139: True,
    143: True, 146: True, 147: True, 148: True,
    149: True, 150: True, 155: True,
    156: True, 157: True, 160: True,
    162: True, 164: True, 166: True,
    167: False,
    168: True, 174: True, 175: True, 177: True, 183: True,
    187: True, 189: True, 191: True,
    194: False,
    195: True, 200: True, 207: True, 215: True, 221: True,
    225: True, 229: True,
    227: False,
    230: False,
}


def build_classification():
    """Return (point_group_of_sg, is_symmorphic_of_sg, symbol_of_sg)."""
    sg_to_pointgroup = {}
    sg_to_centering = {}
    sg_to_symbol = {}
    for hall in range(1, 531):
        info = spglib.get_spacegroup_type(hall)
        if info.number not in sg_to_pointgroup:
            sg_to_pointgroup[info.number] = info.pointgroup_international
            sg_to_centering[info.number] = info.international_short[0]
            sg_to_symbol[info.number] = info.international_short

    if len(sg_to_pointgroup) != 230:
        raise RuntimeError(
            f"expected 230 space groups from spglib, got {len(sg_to_pointgroup)}")

    is_symmorphic = {}
    for sg in range(1, 231):
        entries = WYCKOFF_DB[sg]
        min_mult = min(e.multiplicity for e in entries)
        factor = CENTERING_FACTOR[sg_to_centering[sg]]
        is_symmorphic[sg] = (min_mult == factor)

    return sg_to_pointgroup, is_symmorphic, sg_to_symbol


def validate(point_group_of_sg, is_symmorphic_of_sg, symbol_of_sg):
    n_symmorphic = sum(is_symmorphic_of_sg.values())
    if n_symmorphic != 73:
        raise AssertionError(
            f"expected exactly 73 symmorphic space groups, got {n_symmorphic}")

    mismatches = []
    for sg, expected in REFERENCE_CHECKS.items():
        got = is_symmorphic_of_sg[sg]
        if got != expected:
            mismatches.append((sg, symbol_of_sg[sg], got, expected))
    if mismatches:
        raise AssertionError(f"reference-check mismatches: {mismatches}")

    print(f"Validation OK: {n_symmorphic} symmorphic space groups, "
          f"{len(REFERENCE_CHECKS)}/{len(REFERENCE_CHECKS)} reference checks passed.")


def write_output(point_group_of_sg, is_symmorphic_of_sg):
    lines = []
    lines.append('"""Space-group -> point-group and symmorphic/non-symmorphic')
    lines.append('classification for all 230 space groups.')
    lines.append('')
    lines.append('Auto-generated by scripts/generate_point_group_table.py using')
    lines.append('spglib (point group symbols) and mizuho.data.WYCKOFF_DB (symmorphic')
    lines.append('classification via the minimum-multiplicity-equals-centering-factor')
    lines.append('test -- see that script for the full derivation and validation')
    lines.append('(73 symmorphic space groups total, matching the standard')
    lines.append('crystallographic count; 51 reference examples spot-checked).')
    lines.append('')
    lines.append('Do not edit by hand -- regenerate via:')
    lines.append('    python scripts/generate_point_group_table.py')
    lines.append('"""')
    lines.append('')
    lines.append('from typing import Dict')
    lines.append('')
    lines.append('POINT_GROUP_OF_SG: Dict[int, str] = {')
    for sg in range(1, 231):
        lines.append(f'    {sg}: {point_group_of_sg[sg]!r},')
    lines.append('}')
    lines.append('')
    lines.append('IS_SYMMORPHIC_OF_SG: Dict[int, bool] = {')
    for sg in range(1, 231):
        lines.append(f'    {sg}: {is_symmorphic_of_sg[sg]!r},')
    lines.append('}')
    lines.append('')

    OUTPUT_PATH.write_text("\n".join(lines))
    print(f"wrote {OUTPUT_PATH}")


def main():
    point_group_of_sg, is_symmorphic_of_sg, symbol_of_sg = build_classification()
    validate(point_group_of_sg, is_symmorphic_of_sg, symbol_of_sg)
    write_output(point_group_of_sg, is_symmorphic_of_sg)


if __name__ == "__main__":
    main()
