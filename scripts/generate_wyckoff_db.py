#!/usr/bin/env python3
"""
Dev-only, one-shot generator for mizuho/data/{triclinic,monoclinic,
orthorhombic,tetragonal,trigonal,hexagonal,cubic}.py.

Not part of the shipped package -- run manually (requires the `spglib`
test/dev dependency, via generate_symmetry_ops_table.py's output) to
regenerate the Wyckoff-position tables, then commit the resulting
per-crystal-system files as static data. End users of the installed
`mizuho` package never need this script or spglib at runtime.

Derivation
----------
Every Wyckoff position of every space group is derived first-
principles from mizuho's own true symmetry-operation table
(data/symmetry_ops.py, itself generated by generate_symmetry_ops_table.py)
-- no hand-transcribed data and no dependency on an external Wyckoff-
position table:

1. FIXED-POINT SUBSPACES (per operation): for each symmetry operation
   (R, t), solve (R - I) x ~= -t (mod 1) exactly over the integers via
   Smith Normal Form, enumerating every solution branch (an operation
   can have several parallel fixed subspaces at once, e.g. a 2-fold
   rotation about z through the origin also fixes the parallel axis at
   (1/2, 0, z) via the lattice's periodicity -- a discrete multi-valued
   phenomenon SNF handles exactly, ad-hoc probing does not).
2. CLOSURE UNDER INTERSECTION: repeatedly intersect every pair of
   discovered subspaces (also via SNF, on the combined system) and add
   any new one found, until no new subspace appears. This produces
   every possible site-symmetry-fixed subspace, not just the ones
   individual operations reveal directly (e.g. a point fixed by two
   independent mirrors but by neither mirror's rotation part alone).
3. DEDUPLICATION: two subspaces are the SAME Wyckoff position iff some
   group operation maps the WHOLE of one onto the WHOLE of the other
   (checked by transforming one subspace's point and free directions
   and testing for set-equality with the other) -- not merely whether
   a single matched representative point coincides, which misses
   equivalences that also reparametrise the free coordinate (e.g. a
   centring translation mapping line (x,0,0) onto line (x,1/2,0)).
4. CONFIRMATION: each surviving subspace's true multiplicity (from its
   generic point's stabiliser under the full operation list) and
   canonical Wyckoff letter are confirmed by building a trial structure
   from its orbit (plus a generic "anchor" orbit so the trial structure
   doesn't exhibit extra accidental symmetry) and re-analysing it with
   spglib -- this is the same anchored-trial-structure technique
   generate_point_group_table.py's symmorphic classification and
   tests/validation/test_wyckoff_db_vs_spglib.py both rely on.

Validated against the previous (pyxtal-cross-referenced) database:
reproduces it exactly for 210 of 230 space groups, and finds a more
complete table for the remaining 20 -- all ones with two standard
International-Tables origin choices, where pyxtal's own convention
didn't always match the Hall setting mizuho derives its operations
from. This script has no such external dependency to mismatch against.
"""

import itertools
import sys
from fractions import Fraction
from pathlib import Path

import numpy as np
import spglib

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from mizuho.data.symmetry_ops import SYMMETRY_OPS_OF_SG  # noqa: E402
from mizuho.lattice import get_lattice_system, build_lattice_matrix  # noqa: E402

OUTPUT_DIR = Path(__file__).resolve().parent.parent / "mizuho" / "data"

TOL = 1e-6

LATTICE_PARAMS = {
    "cubic":        {"a": 5.43, "b": 5.43, "c": 5.43},
    "tetragonal":   {"a": 4.7,  "b": 4.7,  "c": 3.1},
    "orthorhombic": {"a": 4.1,  "b": 5.3,  "c": 6.7},
    "hexagonal":    {"a": 4.9,  "b": 4.9,  "c": 7.2, "gamma": 120.0},
    "trigonal":     {"a": 4.9,  "b": 4.9,  "c": 7.2, "gamma": 120.0},
    "monoclinic":   {"a": 5.1,  "b": 6.2,  "c": 7.3, "beta": 99.5},
    "triclinic":    {"a": 4.3,  "b": 5.1,  "c": 6.6,
                      "alpha": 88.0, "beta": 95.0, "gamma": 102.0},
}
ANCHOR_POINT = np.array([0.112837, 0.246893, 0.378512])
GENERIC_PROBES = [Fraction(311288, 1000000), Fraction(472891, 1000000), Fraction(195329, 1000000)]


# ==============================================================================
# 1. Integer Smith Normal Form, with unimodular transformation matrices
# ==============================================================================

def snf_with_transforms(A):
    """A = U @ D @ V; U, V unimodular (det +-1) integer matrices; D
    diagonal, D[0,0] | D[1,1] | ... , all entries >= 0. Uses Python's
    arbitrary-precision ints (object dtype) -- these matrices are tiny
    (3x3, or 3 x (k1+k2) <= 3x6 for subspace intersections)."""
    A = np.array(A, dtype=object)
    n, m = A.shape
    D = A.copy()
    U = np.eye(n, dtype=object)
    V = np.eye(m, dtype=object)

    def swap_rows(M, i, j):
        M[[i, j], :] = M[[j, i], :]

    def swap_cols(M, i, j):
        M[:, [i, j]] = M[:, [j, i]]

    t = 0
    while t < min(n, m):
        sub = D[t:, t:]
        if np.all(sub == 0):
            break

        best = None
        for i in range(t, n):
            for j in range(t, m):
                v = D[i, j]
                if v != 0 and (best is None or abs(v) < abs(best[2])):
                    best = (i, j, v)
        pi, pj, _ = best
        if pi != t:
            swap_rows(D, t, pi); swap_rows(U, t, pi)
        if pj != t:
            swap_cols(D, t, pj); swap_cols(V, t, pj)

        while True:
            for i in range(t + 1, n):
                while D[i, t] != 0:
                    q = D[i, t] // D[t, t]
                    D[i, :] = D[i, :] - q * D[t, :]
                    U[i, :] = U[i, :] - q * U[t, :]
                    if D[i, t] != 0:
                        swap_rows(D, t, i); swap_rows(U, t, i)

            for j in range(t + 1, m):
                while D[t, j] != 0:
                    q = D[t, j] // D[t, t]
                    D[:, j] = D[:, j] - q * D[:, t]
                    V[:, j] = V[:, j] - q * V[:, t]
                    if D[t, j] != 0:
                        swap_cols(D, t, j); swap_cols(V, t, j)

            if np.any(D[t + 1:, t] != 0):
                continue

            pivot = D[t, t]
            offender = None
            for i in range(t + 1, n):
                for j in range(t + 1, m):
                    if D[i, j] % pivot != 0:
                        offender = i
                        break
                if offender is not None:
                    break
            if offender is None:
                break
            D[t, :] = D[t, :] + D[offender, :]
            U[t, :] = U[t, :] + U[offender, :]

        t += 1

    for i in range(min(n, m)):
        if D[i, i] < 0:
            D[i, :] = -D[i, :]
            U[i, :] = -U[i, :]

    return U, D, V


# ==============================================================================
# 2. Solve W @ z ~= b (mod 1) for an n x k integer matrix W (n=3 always here)
# ==============================================================================

def _frac_mod1(x):
    return x - (x.numerator // x.denominator)


def solve_mod1_system(W, b, tol_denom=24):
    """Returns list of branches {"point": [Fraction]*k, "free_dirs": [[int]*k,...]}
    describing every z in R^k with W @ z = b (mod 1), or [] if inconsistent."""
    W = np.array(W, dtype=object)
    n, k = W.shape
    U, D, V = snf_with_transforms(W)

    b_frac = [Fraction(x).limit_denominator(tol_denom) for x in b]
    c = [sum(int(U[i, j]) * b_frac[j] for j in range(n)) for i in range(n)]

    m = min(n, k)
    diag = [int(D[i, i]) for i in range(m)]

    for i in range(m, n):
        if c[i].denominator != 1:
            return []

    free_dims = []
    discrete_choices = []
    for i in range(m):
        d = diag[i]
        if d == 0:
            if c[i].denominator != 1:
                return []
            free_dims.append(i)
            discrete_choices.append(None)
        else:
            vals = [_frac_mod1((c[i] + kk) / d) for kk in range(d)]
            discrete_choices.append(vals)
    for i in range(m, k):
        free_dims.append(i)
        discrete_choices.append(None)

    ranges = [range(len(discrete_choices[i])) if discrete_choices[i] is not None else range(1)
              for i in range(k)]

    branches = []
    for combo in itertools.product(*ranges):
        y = [Fraction(0) if discrete_choices[i] is None else discrete_choices[i][combo[i]]
             for i in range(k)]
        z_point = [sum(int(V[i, j]) * y[j] for j in range(k)) for i in range(k)]
        free_vecs = [[int(V[r, i]) for r in range(k)] for i in free_dims]
        branches.append({"point": z_point, "free_dirs": free_vecs})

    return branches


def fixed_subspace_branches(R, t):
    """Special case of solve_mod1_system with W = R - I (square), giving
    the fixed-point subspace(s) of a single symmetry operation (R, t)
    directly in x-space."""
    A = np.array(R, dtype=object) - np.eye(3, dtype=object)
    return solve_mod1_system(A, [-x for x in t])


# ==============================================================================
# 3. Intersection of two affine subspaces (each: point + integer free dirs)
# ==============================================================================

def _reduce_basis(vectors):
    """Gaussian elimination over Q -- drops linearly dependent rows,
    preserving span. Small dimension (<=3), exact Fraction arithmetic."""
    basis, pivots = [], []
    for v in vectors:
        v = [Fraction(x) for x in v]
        for prow, pcol in zip(basis, pivots):
            if v[pcol] != 0:
                factor = v[pcol] / prow[pcol]
                v = [a - factor * b for a, b in zip(v, prow)]
        pivot_col = next((i for i, x in enumerate(v) if x != 0), None)
        if pivot_col is not None:
            basis.append(v)
            pivots.append(pivot_col)
    return basis, pivots


def _gcd(a, b):
    while b:
        a, b = b, a % b
    return a


def intersect_subspaces(F1, F2):
    V1, V2 = F1["free_dirs"], F2["free_dirs"]
    p1, p2 = F1["point"], F2["point"]
    k1, k2 = len(V1), len(V2)

    if k1 == 0 and k2 == 0:
        if all(_frac_mod1(p1[i] - p2[i]) == 0 for i in range(3)):
            return [{"point": list(p1), "free_dirs": []}]
        return []

    cols = [list(v) for v in V1] + [[-x for x in v] for v in V2]
    W = [[cols[c][r] for c in range(len(cols))] for r in range(3)]
    b = [p2[i] - p1[i] for i in range(3)]

    results = []
    for br in solve_mod1_system(W, b):
        s = br["point"][:k1]
        x_point = [p1[i] + sum(V1[j][i] * s[j] for j in range(k1)) for i in range(3)]

        raw_free_dirs = []
        for fd in br["free_dirs"]:
            fd_s = fd[:k1]
            vec = [sum(V1[j][i] * fd_s[j] for j in range(k1)) for i in range(3)]
            if any(c != 0 for c in vec):
                raw_free_dirs.append(vec)

        free_dirs = []
        if raw_free_dirs:
            reduced, _ = _reduce_basis(raw_free_dirs)
            for v in reduced:
                lcm = 1
                for f in v:
                    lcm = lcm * f.denominator // _gcd(lcm, f.denominator)
                free_dirs.append([int(f * lcm) for f in v])

        results.append({"point": [Fraction(x) for x in x_point], "free_dirs": free_dirs})

    return results


def _rank(vectors):
    reduced, _ = _reduce_basis(vectors)
    return len(reduced)


def _in_real_span(v, basis):
    if not basis:
        return all(x == 0 for x in v)
    return _rank(basis) == _rank(basis + [v])


def point_in_subspace(q, F):
    p, V = F["point"], F["free_dirs"]
    if not V:
        return all(_frac_mod1(q[i] - p[i]) == 0 for i in range(3))
    W = [[V[j][i] for j in range(len(V))] for i in range(3)]
    b = [q[i] - p[i] for i in range(3)]
    return len(solve_mod1_system(W, b)) > 0


def is_subset(A, B):
    if not point_in_subspace(A["point"], B):
        return False
    return all(_in_real_span(v, B["free_dirs"]) for v in A["free_dirs"])


def subspaces_equal(A, B):
    return is_subset(A, B) and is_subset(B, A)


# ==============================================================================
# 4. Closure + orbit-equivalence deduplication
# ==============================================================================

def collect_elementary_subspaces(rotations, translations):
    subspaces = []
    for R, t in zip(rotations, translations):
        subspaces.extend(fixed_subspace_branches(R, t))
    return subspaces


def closure(elementary_subspaces, max_rounds=6):
    all_subspaces = []

    def add_if_new(F):
        if any(subspaces_equal(F, existing) for existing in all_subspaces):
            return False
        all_subspaces.append(F)
        return True

    for F in elementary_subspaces:
        add_if_new(F)

    for _round in range(max_rounds):
        changed = False
        current = list(all_subspaces)
        for i in range(len(current)):
            for j in range(i, len(current)):
                for result in intersect_subspaces(current[i], current[j]):
                    if add_if_new(result):
                        changed = True
        if not changed:
            break
    return all_subspaces


def true_stabilizer_size(rotations, translations, point_frac):
    p = np.array([float(x) for x in point_frac])
    count = 0
    for R, t in zip(rotations, translations):
        q = np.array(R, dtype=float) @ p + np.array(t, dtype=float)
        d = q - p
        d -= np.round(d)
        if np.all(np.abs(d) < TOL):
            count += 1
    return count


def expand_orbit(rotations, translations, point_frac):
    p = np.array([float(x) for x in point_frac])
    raw = [(np.array(R, dtype=float) @ p + np.array(t, dtype=float)) % 1.0
           for R, t in zip(rotations, translations)]
    uniq = []
    for q in raw:
        if not any(np.all(np.abs((np.array(u) - q + 0.5) % 1.0 - 0.5) < TOL) for u in uniq):
            uniq.append(q)
    return uniq


def generic_point_on(F):
    p = list(F["point"])
    for k, v in enumerate(F["free_dirs"]):
        s = GENERIC_PROBES[k % 3]
        p = [p[i] + s * v[i] for i in range(3)]
    return p


def apply_op_to_subspace(R, t_frac, F):
    p = F["point"]
    new_point = [sum(int(R[i][j]) * p[j] for j in range(3)) + t_frac[i] for i in range(3)]
    new_free_dirs = [[sum(int(R[i][j]) * v[j] for j in range(3)) for i in range(3)]
                     for v in F["free_dirs"]]
    return {"point": new_point, "free_dirs": new_free_dirs}


def same_wyckoff_position(F1, F2, rotations, translations):
    """F1 and F2 are the same Wyckoff position iff some group operation
    maps the WHOLE of F1 onto the WHOLE of F2 -- checking a single
    matched representative point is not enough, since e.g. a centring
    translation maps line (x,0,0) onto the parallel line (x,1/2,0)
    while also shifting/reparametrising the free coordinate."""
    if len(F1["free_dirs"]) != len(F2["free_dirs"]):
        return False
    for R, t in zip(rotations, translations):
        t_frac = [Fraction(x).limit_denominator(24) for x in t]
        if subspaces_equal(apply_op_to_subspace(R, t_frac, F1), F2):
            return True
    return False


def dedupe_by_orbit(subspaces, rotations, translations):
    annotated = []
    for F in subspaces:
        gp = generic_point_on(F)
        stab = true_stabilizer_size(rotations, translations, gp)
        mult = len(rotations) // stab
        annotated.append((F, gp, mult))
    # most general (highest free-dim) form first, so it's the one kept
    annotated.sort(key=lambda item: (-len(item[0]["free_dirs"]), item[2]))

    kept = []
    for F, gp, mult in annotated:
        if any(m2 == mult and same_wyckoff_position(F, F2, rotations, translations)
               for F2, _, m2 in kept):
            continue
        kept.append((F, gp, mult))
    return kept


# ==============================================================================
# 5. spglib letter/site-symmetry confirmation + coord_template extraction
# ==============================================================================

def confirm_letter(sg, rotations, translations, orbit_points):
    lattice = build_lattice_matrix(LATTICE_PARAMS[get_lattice_system(sg)])
    anchor_orbit = expand_orbit(rotations, translations, ANCHOR_POINT)
    anchor_orbit = [p for p in anchor_orbit
                    if not any(np.all(np.abs((np.array(p) - np.array(q) + 0.5) % 1.0 - 0.5) < TOL)
                               for q in orbit_points)]
    positions = list(orbit_points) + list(anchor_orbit)
    numbers = [14] * len(orbit_points) + [8] * len(anchor_orbit)
    try:
        ds = spglib.get_symmetry_dataset((lattice, positions, numbers), symprec=1e-4)
    except Exception:
        return None
    if ds is None or ds.number != sg:
        return None
    letters = set(ds.wyckoffs[:len(orbit_points)])
    eq = set(ds.equivalent_atoms[:len(orbit_points)])
    if len(letters) != 1 or len(eq) != 1:
        return None
    return list(letters)[0]


def subspace_to_coord_template(F):
    k = len(F["free_dirs"])
    names = ["x", "y", "z"][:k]
    p = F["point"]
    slots = []
    for i in range(3):
        coeffs = {names[j]: F["free_dirs"][j][i]
                  for j in range(k) if F["free_dirs"][j][i] != 0}
        offset = _frac_mod1(p[i])
        if not coeffs:
            slots.append(float(offset))
        elif offset == 0:
            slots.append(coeffs)
        else:
            slots.append((coeffs, float(offset)))
    return tuple(slots), names


def derive_space_group(sg, rotations, translations):
    n_ops = len(rotations)
    subs = closure(collect_elementary_subspaces(rotations, translations))
    deduped = dedupe_by_orbit(subs, rotations, translations)

    entries = []
    for F, gp, mult in deduped:
        orbit = expand_orbit(rotations, translations, gp)
        if len(orbit) != mult:
            raise AssertionError(f"SG{sg}: orbit size {len(orbit)} != true_mult {mult}")
        letter = confirm_letter(sg, rotations, translations, orbit)
        if letter is None:
            raise AssertionError(f"SG{sg}: spglib re-analysis failed for a mult-{mult} position")
        coord_template, free_params = subspace_to_coord_template(F)
        entries.append({
            "letter": letter, "multiplicity": mult,
            "free_params": free_params, "coord_template": coord_template,
        })

    letters = [e["letter"] for e in entries]
    if len(letters) != len(set(letters)):
        raise AssertionError(f"SG{sg}: duplicate letters {letters}")
    if not any(e["multiplicity"] == n_ops for e in entries):
        raise AssertionError(f"SG{sg}: no general position found (n_ops={n_ops})")
    return entries


# ==============================================================================
# 6. Write the 7 per-crystal-system data files
# ==============================================================================

SYSTEMS = [
    ("triclinic",    range(1, 3),    "SG 1-2"),
    ("monoclinic",   range(3, 16),   "SG 3-15"),
    ("orthorhombic", range(16, 75),  "SG 16-74"),
    ("tetragonal",   range(75, 143), "SG 75-142"),
    ("trigonal",     range(143, 168), "SG 143-167"),
    ("hexagonal",    range(168, 195), "SG 168-194"),
    ("cubic",        range(195, 231), "SG 195-230"),
]


def _format_dict(d):
    return "{" + ", ".join(f"{k!r}: {v}" for k, v in d.items()) + "}"


def _format_slot(slot):
    if isinstance(slot, tuple):
        coeffs, offset = slot
        return f"({_format_dict(coeffs)}, {offset!r})"
    if isinstance(slot, dict):
        return _format_dict(slot)
    return repr(float(slot))


def _format_entry(e):
    slots = ", ".join(_format_slot(s) for s in e["coord_template"])
    return f'WyckoffEntry({e["letter"]!r}, {e["multiplicity"]}, {e["free_params"]!r}, ({slots}))'


def write_data_files(all_entries):
    for name, sg_range, label in SYSTEMS:
        lines = [
            f'"""Wyckoff position database: {name} space groups ({label}).',
            "",
            "Derived first-principles from spglib's true symmetry operations",
            "(see scripts/generate_wyckoff_db.py): every space group's full set",
            "of Wyckoff positions is found by collecting each operation's fixed-",
            "point subspace (via Smith Normal Form over the integers), closing",
            "under pairwise intersection, deduplicating positions related by a",
            "group operation, and confirming each survivor's multiplicity and",
            "canonical letter through an independent spglib re-analysis. No",
            "hand-transcribed data and no external Wyckoff-table dependency.",
            "No generator callables: orbits are expanded generically at",
            "runtime via data/_orbit.py.",
            '"""',
            "",
            "from typing import Dict, List",
            "",
            "from ._wyckoff_entry import WyckoffEntry",
            "",
            "",
            "def get_entries() -> Dict[int, List[WyckoffEntry]]:",
            f'    """Return the Wyckoff entries for {label}."""',
            "    db: Dict[int, List[WyckoffEntry]] = {}",
            "",
        ]
        for sg in sg_range:
            rows = sorted(all_entries.get(sg, []),
                          key=lambda e: (e["multiplicity"], e["letter"]))
            if not rows:
                continue
            lines.append(f"    db[{sg}] = [")
            for e in rows:
                lines.append(f"        {_format_entry(e)},")
            lines.append("    ]")
            lines.append("")
        lines.append("    return db")
        lines.append("")

        path = OUTPUT_DIR / f"{name}.py"
        path.write_text("\n".join(lines))
        print(f"wrote {path} ({len(sg_range)} SGs, "
              f"{sum(len(all_entries.get(sg, [])) for sg in sg_range)} entries)")


def main():
    all_entries = {}
    for sg in range(1, 231):
        rotations, translations = SYMMETRY_OPS_OF_SG[sg]
        rotations = np.array(rotations, dtype=float)
        translations = np.array(translations, dtype=float)
        all_entries[sg] = derive_space_group(sg, rotations, translations)

    total = sum(len(v) for v in all_entries.values())
    print(f"Derived {total} Wyckoff positions across 230 space groups.")
    write_data_files(all_entries)


if __name__ == "__main__":
    main()
